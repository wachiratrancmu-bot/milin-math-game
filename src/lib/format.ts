/** อักษรนำตัวเลือก ตามรูปแบบข้อสอบของโรงเรียน */
export const CHOICE_KEYS = ['ก', 'ข', 'ค', 'ง']

/** จัดรูปแบบคำตอบที่กดจากแป้นให้อ่านง่าย: 2+4=6 → 2 + 4 = 6 */
export const formatEntry = (value: string) =>
  value
    .replace(/([+−=])/g, ' $1 ')
    .replace(/\s+/g, ' ')
    .trim()
